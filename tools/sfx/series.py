def db(g):
    return 10 ** (g / 20)


def outfit(rel, note, dur, points):
    """Sustained note (brass "sus" or strings) tuned, cut at dur seconds under an envelope (points in dB)."""
    x = inst(rel, note)[:int(dur * SR)]
    return x * curve_of(len(x), points)


