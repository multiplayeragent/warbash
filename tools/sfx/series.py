def already_done(lang, sid):
    """Line already shipped (NEW_VOICES): its MP3 exists and its synthesis WAV is missing"""
    return NEW_SOUNDS and (C.ROOT / 'assets' / 'sfx' / f'voice_{lang}' / f'{sid}.mp3').exists() and not (TTS / lang / f'{sid}.wav').exists()


def phrase(lang, sid):
    """(text, full settings) of a line"""
    v = PHRASES[lang][sid]
    wording, clean = (v, {}) if isinstance(v, str) else v
    return wording, {**TTS_SETTINGS, 'tempo': 1.0, **clean}


def chatterbox_fix():
    """chatterbox-tts 0.1.7 raises IndexError on a very short line ("One."): its alignment analysis
    (AlignmentStreamAnalyzer.step) takes the text tokens except the last five, an empty list when the text has
    five or fewer. On this error, the frame's analysis is skipped (the model then stops by itself)."""
    from chatterbox.models.t3.inference import alignment_stream_analyzer as asa
    if getattr(asa.AlignmentStreamAnalyzer.step, 'corrected', False): return
    step = asa.AlignmentStreamAnalyzer.step

    def step_on(self, logits, next_token=None):
        try: return step(self, logits, next_token=next_token)
        except IndexError:
            self.curr_frame_pos += 1
            return logits
    step_on.corrected = True
    asa.AlignmentStreamAnalyzer.step = step_on


def tts_generate(force=False):
    """Generates assets_src/sfx/src/tts/<language>/<id>.wav (24 kHz) with Chatterbox Multilingual if the chatterbox-tts package is installed.
    A file is only redone if its text, its reference voice or its settings changed (noted beside it in <id>.txt), or with force.
    Returns False if the model is not available."""
    import hashlib
    try:
        import torch, torchaudio
        from chatterbox.mtl_tts import ChatterboxMultilingualTTS
    except ImportError:
        return False
    os.environ.setdefault('HF_HUB_DISABLE_XET', '1')  # download through the standard Hugging Face URLs
    chatterbox_fix()
    model_name = None
    for lang, table in PHRASES.items():
        ref = VOICE_REF / VOICES[lang]['ref']
        footprint = hashlib.sha1(ref.read_bytes()).hexdigest()[:12]
        for sid in table:
            if already_done(lang, sid): continue
            wording, r = phrase(lang, sid)
            p = TTS / lang / f'{sid}.wav'; note = p.with_suffix('.txt')
            key = f"chatterbox-mtl|{footprint}|{r['seed']}|{r['exag']}|{r['cfg']}|{r['temp']}|{r['tempo']}|{wording}"
            if p.exists() and note.exists() and note.read_text(encoding='utf-8') == key and not force: continue
            if model_name is None:
                torch.set_num_threads(max(1, os.cpu_count() or 1))
                model_name = ChatterboxMultilingualTTS.from_pretrained(device='cuda' if torch.cuda.is_available() else 'cpu')
            torch.manual_seed(r['seed'])
            wav = model_name.generate(wording, language_id=lang, audio_prompt_path=str(ref), exaggeration=r['exag'], cfg_weight=r['cfg'], temperature=r['temp'])
            p.parent.mkdir(parents=True, exist_ok=True)
            unprocessed = p.with_suffix('.unprocessed.wav'); torchaudio.save(str(unprocessed), wav, model_name.sr)
            textFilter = ['-af', f"atempo={r['tempo']}"] if r['tempo'] != 1.0 else []
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(unprocessed), *textFilter, '-ar', '24000', '-ac', '1', '-c:a', 'pcm_s24le', str(p)], check=True)
            unprocessed.unlink()
            note.write_text(key, encoding='utf-8')
    return True


def speech_end(x, cutpoint=-40, gap=0.15):
    """Cuts what follows the sentence: at the first gap of `gap` s below `cutpoint` dB from the peak (10 ms slices) after the start
    of speech. After the last syllable, Chatterbox often leaves a breath, the background noise imitated from the reference voice,
    or an invented ending (extra syllables); the lines have no inner pause that long."""
    h = int(0.01 * SR); n = len(x) // h
    r = 20 * np.log10(np.sqrt(np.mean(x[:n * h].reshape(n, h) ** 2, axis=1)) + 1e-9); r -= r.max()
    startpoint, k, low = int(np.argmax(r > -30)), int(round(gap / 0.01)), r < cutpoint
    for i in range(startpoint, n - k + 1):
        if low[i:i + k].all(): return x[:i * h + int(0.03 * SR)]
    return x


def radio_voice(x, seed_val):
    """Radio processing: band-pass 300 Hz-3.4 kHz, presence, compression, light saturation, very low noise."""
    x = C.trim(x, -50, 0.003)                        # keeps the closure of an initial consonant (d, b, g)
    x = x[:C.tail_end(x, -50)]
    x = af(x, hp(300), lp(3400), eq(1800, 3, 0.9), eq(700, -2, 1))
    x = compress(x, -20, 4, 4, 90)
    x = C.norm(x, -1)
    x = np.tanh(2.2 * x) / np.tanh(2.2)              # soft saturation of the audio stage
    x = af(x, lp(3600))
    whoosh = af(np.random.default_rng(seed_val).standard_normal(len(x)), hp(400), lp(3200))
    r = np.sqrt(np.mean(x ** 2))
    whoosh *= r * 10 ** (-36 / 20) / np.sqrt(np.mean(whoosh ** 2))
    return C.fade(x + C.fade(whoosh, 0.01, 0.03), 0.001, 0.04)


def voices():
    """v_*: radio voices in English (voice_en), VOICE_MAX s at most, peak -1 dBFS."""
    tts_generate()
    for k, (lang, table) in enumerate(PHRASES.items()):
        for j, sid in enumerate(table):
            if already_done(lang, sid): continue
            wording, r = phrase(lang, sid)
            p = TTS / lang / f'{sid}.wav'
            if not p.exists():
                raise SystemExit(f'{p} is missing: install chatterbox-tts to generate the voices (see tts_generate)')
            x = radio_voice(speech_end(C.load(p)), 1000 * k + j)
            if len(x) > VOICE_MAX * SR: raise ValueError(f'{lang}/{sid}: {len(x) / SR:.2f} s (at most {VOICE_MAX} s: faster tempo, or another draw)')
            tempo = f", sped up x{r['tempo']}" if r['tempo'] != 1.0 else ''
            export_pack(f'voice_{lang}', sid, x, 'chatterbox', f'tts/{lang}/{sid}.wav',
                   f"“{wording}” (Chatterbox Multilingual, {VOICES[lang]['naming']}, draw {r['seed']}, expressiveness {r['exag']}{tempo}); "
                   f"cut at the first gap after the sentence; band-pass 300 Hz-3.4 kHz, compression, light saturation, radio noise at -36 dB")
            layer_of(sid, VOICES[lang]['source'], f"tools/sfx/voice_ref/{VOICES[lang]['ref']}", 'reference voice (timbre imitated by the model)', pack=f'voice_{lang}')


