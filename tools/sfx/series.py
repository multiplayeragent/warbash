# Processing tools

def src(rel, startpoint=None, duration_s=None):
    """Source decoded to mono 48 kHz (excerpt startpoint..startpoint+duration_s s)."""
    return C.load(C.SRC / rel, start=startpoint, dur=duration_s)


def af(x, *filters):
    """ffmpeg filter chain (empty elements are ignored)."""
    ch = ','.join(f for f in filters if f)
    return C.ff(x, ch) if ch else x


def hp(f, poles=2):
    """12 dB/octave high-pass per stage (poles stages)."""
    return ','.join([f'highpass=f={f}:poles=2'] * poles)


def lp(f, poles=2):
    return ','.join([f'lowpass=f={f}:poles=2'] * poles)


def eq(f, g, q=1.0):
    return f'equalizer=f={f}:t=q:w={q}:g={g}'


def low_shelf(f, g):
    return f'lowshelf=f={f}:g={g}'


def high_tone(f, g):
    return f'highshelf=f={f}:g={g}'


def velocity(x, r):
    """Sped-up (r > 1) or slowed playback: pitch and duration change together (soxr resampling)."""
    if abs(r - 1) < 1e-6: return x
    # asetrate declares the rate SR*r then aresample goes back to SR: the signal is replayed r times faster
    return C.ff(x, f'asetrate={int(round(SR * r))},aresample={SR}:resampler=soxr')


def semitones(x, n):
    return velocity(x, 2 ** (n / 12))


def toward(x, f0, objective):
    """Transposes a note from f0 to the target frequency."""
    return velocity(x, objective / f0)


def varispeed(x, rate_of):
    """Variable-speed playback: rate_of[n] = playback speed at output sample n (Doppler, slow motion).
    Cubic interpolation (Catmull-Rom); the output stops at the end of the source."""
    pos = np.concatenate([[0.0], np.cumsum(rate_of[:-1])])
    pos = pos[pos < len(x) - 3]
    i = np.floor(pos).astype(int); t = pos - i
    xp = np.concatenate([[x[0]], x, [x[-1], x[-1]]])
    p0, p1, p2, p3 = xp[i], xp[i + 1], xp[i + 2], xp[i + 3]
    return p1 + 0.5 * t * (p2 - p0 + t * (2 * p0 - 5 * p1 + 4 * p2 - p3 + t * (3 * (p1 - p2) + p3 - p0)))


def curve_of(n, points):
    """Per-sample gain (n samples) interpolated in dB between points (t in s, dB)."""
    t = np.arange(n) / SR
    ts, gs = zip(*points)
    return 10 ** (np.interp(t, ts, gs) / 20)


def rms_smooth(x, fen):
    """RMS envelope smoothed over fen seconds."""
    k = max(1, int(fen * SR)); m = min(k, len(x) - 1)
    p = np.pad(x ** 2, (m, m), mode='reflect')       # mirrored edges: no false envelope dips at the ends
    e = np.convolve(p, np.ones(k) / k, 'same')[m:m + len(x)]
    return np.sqrt(np.maximum(e, 1e-12))


def flatten(x, fen=0.4):
    """Removes slow level variations (approach, moving away): signal / smoothed envelope."""
    e = rms_smooth(x, fen)
    return x * (np.median(e) / e)


def period_s(x, tmin, tmax, f_env=None):
    """Dominant period (s) of the envelope between tmin and tmax (rotor blades, rate of fire)."""
    y = af(x, lp(f_env)) if f_env else x
    e = np.abs(y); k = int(0.004 * SR)
    e = np.convolve(e, np.ones(k) / k, 'same')[::24]; e = e - e.mean()
    n = 1 << int(np.ceil(np.log2(2 * len(e))))
    ac = np.fft.irfft(np.abs(np.fft.rfft(e, n)) ** 2)[:len(e)]
    a, b = int(tmin * SR / 24), int(tmax * SR / 24)
    i = a + int(np.argmax(ac[a:b]))
    y0, y1, y2 = ac[i - 1], ac[i], ac[i + 1]
    return (i + 0.5 * (y0 - y2) / (y0 - 2 * y1 + y2)) * 24 / SR


def join_at(x, n0, xf, lmin, lmax, f_env=200):
    """Loop length (samples, between lmin and lmax) that best aligns x[n0+L : n0+L+xf] with x[n0 : n0+xf]
    (correlation of the low part, where the blade beats or gunshots are)."""
    y = af(x, lp(f_env))
    lmax = min(lmax, len(y) - n0 - xf)
    a = y[n0:n0 + xf]; best, bl = -2, lmin
    for L in range(lmin, lmax + 1, 4):
        b = y[n0 + L:n0 + L + xf]
        c = float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))
        if c > best: best, bl = c, L
    for L in range(max(lmin, bl - 4), min(lmax, bl + 4) + 1):
        b = y[n0 + L:n0 + L + xf]
        c = float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-12))
        if c > best: best, bl = c, L
    return bl, best


def make_loop(x, L, xf):
    """Loop of L samples from x (at least L + xf samples): the end x[L:L+xf] is crossfaded
    onto the start. Fade law: gains a, b normalized by the correlation r of the two pieces (a² + b² + 2rab = 1),
    to keep a constant level whether the pieces are correlated (aligned rotor) or not (noise)."""
    head = x[:xf]; tail = x[L:L + xf]
    r = float(np.dot(head, tail) / (np.linalg.norm(head) * np.linalg.norm(tail) + 1e-12))
    u = (np.arange(xf) + 0.5) / xf
    a = np.cos(u * np.pi / 2) ** 2; b = np.sin(u * np.pi / 2) ** 2
    g = 1 / np.sqrt(a * a + b * b + 2 * max(r, -0.5) * a * b)
    y = x[:L].copy()
    y[:xf] = (tail * a + head * b) * g
    return y


def compress(x, cutpoint=-18, ratio=2.5, attack_time=20, release_t=250):
    """Soft compression (the signal is first brought back to -1 dBFS so the threshold makes sense)."""
    x = C.norm(x, -1)
    return af(x, f'acompressor=threshold={10 ** (cutpoint / 20):.5f}:ratio={ratio}:attack={attack_time}:release={release_t}:knee=6')


def startpoint(x, cutpoint=-40, pre=0.0005):
    """Start at the attack (at most 0.5 ms kept before it)."""
    return C.trim(x, cutpoint, pre)


def cut_end(x, dur, fout):
    """Keeps dur seconds at most, fade-out of fout seconds."""
    return C.fade(x[:int(dur * SR)], 0.0005, fout)


