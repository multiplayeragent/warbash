/* ==========================================================================
   INSTALLABLE APP (PWA): on a phone, the game is played installed. It is added to the home screen and then opens fullscreen,
   without an address bar (manifest generated by build.py, service worker assets/pwa/sw.js copied into dist/).
   - the service worker only caches the fingerprinted files (/tex, /maps, /icons): the page, the API and version.json stay
     always fresh, the game's automatic update (09h-update.js) doesn't change;
   - in a touchscreen browser, the game doesn't start: the install window shows first, right away (in portrait
     as in landscape: "Rotate your device" doesn't come first), and the game is only launched (99-start.js) once the app has been
     opened from its icon, or if the player opts out ("Can't install?", then "Play in the browser anyway", for one
     week):
       Android (Chrome, Edge, Samsung Internet): the browser announces installation ("beforeinstallprompt"), a button starts it;
       iPhone and iPad: Apple offers no prompt, the window shows the gesture (Share, "Add to Home Screen");
       other browser without an announcement: the gesture in the browser menu;
   - the opt-out exists because installation is sometimes impossible (browser embedded in an app, browser without
     installation): without it, those players couldn't play at all;
   - old account links received by e-mail (?verif, ?mdp: the Profile says they no longer work), ?inBrowser and ?diag (graphics report)
     pass without the window; an invite link (?lobby) is kept
     for a while for the app (which opens without the address);
   - a discreet main menu card reminds those playing in the browser about installation. The game launched from the icon no longer mentions it.
   See README, "Mobile version".
   ========================================================================== */
const PWA = { prompt: null, ios: false, standalone: false, wait: 0, gate: false, alt: false, done: false, start: null, title0: '', lead0: '' };
const PWA_BROWSER = 7 * 24 * 3600 * 1000, PWA_INSTALLED = 90 * 24 * 3600 * 1000, PWA_SALON = 30 * 60 * 1000;

const pwaGet = (k) => { try { return +localStorage.getItem(k) || 0; } catch (e) { return 0; } };
const pwaSet = (k) => { try { localStorage.setItem(k, String(Date.now())); } catch (e) { /* ignored */ } };
function pwaStandalone() {
  try { return matchMedia('(display-mode: fullscreen)').matches || matchMedia('(display-mode: standalone)').matches || matchMedia('(display-mode: minimal-ui)').matches || !!navigator.standalone; } catch (e) { return false; }
}
const pwaInstalled = () => Date.now() - pwaGet('dc_pwa_in') < PWA_INSTALLED; // installed on this device (or launched from the icon) less than 90 days ago
const pwaBrowserOk = () => Date.now() - pwaGet('dc_pwa_ok') < PWA_BROWSER; // opt-out in effect: playing in the browser accepted
/* Should installation be advertised (menu card)? Touchscreen, outside the installed app */
const pwaCan = () => COARSE && !deckLooksLike() && !PWA.standalone && !pwaInstalled();
const pwaMode = () => (PWA.done ? 'done' : PWA.prompt ? 'prompt' : PWA.ios ? 'ios' : PWA.gate && pwaInstalled() ? 'installed' : PWA.wait ? 'wait' : 'manual');

/* Main menu card: discreet reminder, always there as long as the game isn't installed */
function pwaCard() { $('pwaCard').classList.toggle('hidden', !pwaCan()); }

const PWA_IC = {
  share: '<path d="M12 3v12M8 7l4-4 4 4"/><path d="M7 11H6a1 1 0 0 0-1 1v8a1 1 0 0 0 1 1h12a1 1 0 0 0 1-1v-8a1 1 0 0 0-1-1h-1"/>',
  add: '<rect x="4" y="4" width="16" height="16" rx="3"/><path d="M12 8v8M8 12h8"/>',
  dots: '<circle cx="12" cy="5" r="1.5"/><circle cx="12" cy="12" r="1.5"/><circle cx="12" cy="19" r="1.5"/>',
  ok: '<path d="M5 12.5l4.5 4.5L19 7.5"/>',
};
/* Window content depending on the case: install button, or the gestures to do by hand */
function pwaRender() {
  const m = pwaMode(), steps = $('poSteps'), note = $('poNote'), box = $('pwaOffer');
  const L = m === 'ios'
    ? [['share', _t('Tap Share in Safari (the square with an arrow pointing up).')], ['add', _t('Choose "Add to Home Screen".')], ['ok', _t('Tap Add, then launch the game from its new icon.')]]
    : m === 'manual'
      ? [['dots', _t('Open the browser menu (the three dots).')], ['add', _t('Tap "Install app" or "Add to Home screen".')], ['ok', _t('Confirm, then launch the game from its new icon.')]]
      : [];
  steps.innerHTML = L.map(([ic, tx]) => `<li><svg viewBox="0 0 24 24" aria-hidden="true">${PWA_IC[ic]}</svg><span>${esc(tx)}</span></li>`).join('');
  steps.classList.toggle('hidden', !L.length);
  box.classList.toggle('steps', L.length > 0); // gestures by hand: on a short screen, they take the place of the reasons
  box.classList.toggle('plain', m === 'done' || m === 'installed'); // nothing to install: neither reasons nor button
  $('poTitle').textContent = m === 'done' ? _t('Installed!') : m === 'installed' ? _t('The game is already installed') : PWA.title0;
  $('poLead').textContent = m === 'done' ? _t('Open War Bash from its icon on your home screen.') : m === 'installed' ? _t('Open it from its icon. Full screen, same progress.') : PWA.lead0;
  note.textContent = m === 'ios' ? _t('On iPhone and iPad, the game is played in landscape. Turn off the orientation lock.') : '';
  note.classList.toggle('hidden', m !== 'ios');
  const go = $('poGo'); go.classList.toggle('hidden', m !== 'prompt' && m !== 'wait'); go.disabled = m === 'wait'; // waiting for the browser's announcement: the button isn't active yet
  // opt-out: requested ("Can't install?") or offered right away when the game is already installed; outside blocking (menu card), "Later" simply closes
  $('poHelp').classList.toggle('hidden', !PWA.gate || PWA.alt || m === 'installed');
  $('poAlt').classList.toggle('hidden', PWA.gate && !PWA.alt && m !== 'installed');
  $('poAltTxt').classList.toggle('hidden', !PWA.gate);
  $('poNo').textContent = PWA.gate ? _t('Play in the browser anyway') : _t('Later');
}
/* Blocks the game's startup behind the install window (called by 99-start.js: start launches the game when the player opts out) */
function pwaGate(start) {
  const q = new URLSearchParams(location.search);
  if (!COARSE || deckLooksLike() || PWA.standalone || pwaBrowserOk() || q.has('verif') || q.has('mdp') || q.has('inBrowser') || q.has('diag') || q.has('trial') || q.has('devTool')) return false;
  const lobby = q.get('lobby'); if (lobby) { try { localStorage.setItem('dc_lobby', JSON.stringify({ c: String(lobby).slice(0, 8), t: Date.now() })); } catch (e) { /* ignored */ } }
  PWA.gate = true; PWA.start = start; PWA.wait = PWA.ios ? 0 : setTimeout(() => { PWA.wait = 0; pwaRender(); }, 3500);
  document.body.classList.add('gated'); pwaRender(); $('pwaOffer').classList.remove('hidden'); gpuLog('install gate shown');
  return true;
}
/* Invitation received in the browser, then opened in the app: the lobby code is kept for half an hour */
function pwaLobby() {
  try {
    const v = JSON.parse(localStorage.getItem('dc_lobby') || 'null'); localStorage.removeItem('dc_lobby');
    return v && Date.now() - v.t < PWA_SALON && PWA.standalone ? v.c : null;
  } catch (e) { return null; }
}
/* Opt-out: the player plays in the browser (one week); outside blocking, the window simply closes */
function pwaBrowser() {
  $('pwaOffer').classList.add('hidden');
  if (!PWA.gate) { pwaCard(); return; }
  gpuLog('install gate left: browser'); pwaSet('dc_pwa_ok'); PWA.gate = false; PWA.alt = false; document.body.classList.remove('gated'); pwaCard();
  const f = PWA.start; PWA.start = null; if (f) f();
}
async function pwaInstall() {
  const p = PWA.prompt; if (!p) return;
  PWA.prompt = null;
  let accepted = false;
  try { p.prompt(); const r = await p.userChoice; accepted = !!r && r.outcome === 'accepted'; } catch (e) { /* invite already used: no consequence */ }
  if (accepted) pwaDone(); else pwaRender(); // refused: the by-hand gestures take over
}
/* Installed: when blocking, the window stays and says to open the icon; otherwise it closes */
function pwaDone() {
  PWA.prompt = null; pwaSet('dc_pwa_in'); gpuLog('app installed');
  if (PWA.gate) { PWA.done = true; pwaRender(); } else $('pwaOffer').classList.add('hidden');
  pwaCard();
}
function pwaInit() {
  PWA.standalone = pwaStandalone();
  if (PWA.standalone) pwaSet('dc_pwa_in'); // launched from the icon: remembered for the browser on the same phone
  PWA.ios = /iPad|iPhone|iPod/.test(navigator.userAgent) || (navigator.platform === 'MacIntel' && navigator.maxTouchPoints > 1);
  PWA.title0 = $('poTitle').textContent; PWA.lead0 = $('poLead').textContent; // ordinary window texts (already translated), restored after a special case
  // service worker: after the page loads, so as not to slow startup
  if ('serviceWorker' in navigator) {
    const reg = () => { navigator.serviceWorker.register('sw.js', { scope: './' }).catch(() => { /* outside HTTPS, or denied: the game works without it */ }); };
    if (document.readyState === 'complete') reg(); else addEventListener('load', reg, { once: true });
  }
  $('poGo').addEventListener('click', () => pwaInstall());
  $('poHelp').addEventListener('click', () => { PWA.alt = true; pwaRender(); $('poNo').scrollIntoView({ block: 'nearest' }); });
  $('poNo').addEventListener('click', () => pwaBrowser());
  $('pwaOffer').addEventListener('keydown', (e) => { if (e.code === 'Escape') { e.preventDefault(); e.stopImmediatePropagation(); if (!PWA.gate) $('pwaOffer').classList.add('hidden'); } }, true);
  // the menu card: installs with a tap when possible, otherwise reopens the window and its gestures
  $('pwaGo').addEventListener('click', () => { if (PWA.prompt) pwaInstall(); else { pwaRender(); $('pwaOffer').classList.remove('hidden'); } });
  addEventListener('beforeinstallprompt', (e) => {
    e.preventDefault(); PWA.prompt = e;
    if (PWA.wait) { clearTimeout(PWA.wait); PWA.wait = 0; } // the announcement arrived during the wait: the button becomes active
    if (!$('pwaOffer').classList.contains('hidden')) pwaRender(); // window opened with the by-hand gestures: the button takes over
    pwaCard();
  });
  addEventListener('appinstalled', () => pwaDone());
  pwaCard();
}
pwaInit();
